package com.remasteragent.llm.config;

/**
 * 调用用途 —— 多模型路由的路由键。
 *
 * <p>不同节点的「智能需求」和「调用频次」差得很远，用同一个模型伺候所有节点是成本失控的常见原因：
 * 一个任务里 REWRITE 会被调用几十次（每个文件、每次回退重写各一次），
 * 而 ANALYZE/PLAN 往往只有一两次。把最贵的模型放在最高频的节点上，
 * 单任务成本会被改写节点吃掉绝大部分。
 */
public enum LlmPurpose {
    /** 读懂代码结构。低频，可以用强模型 */
    ANALYZE,
    /** 代码改写。**高频**，是成本大头，适合用便宜档 */
    REWRITE,
    /** 判断失败原因是代码问题还是测试问题。中频 */
    VALIDATE
}
