package com.remasteragent.core.progress;

/**
 * 进度订阅链路的「可观测性与可恢复性」口子 —— 只有两个动作：读信号、重建订阅。
 *
 * <h2>为什么单独定义，而不是直接依赖 {@code RedisProgressEventSubscriber}</h2>
 * <p>看门狗（{@code ProgressLinkWatchdog}）的判据是纯逻辑：信号有多旧、该不该重建。
 * 这部分必须能被确定性单测覆盖 —— 「链路静默多久才算死」这种东西靠端到端去试是试不出来的：
 * 真正的故障只在公网连接被回收时才复现，等一次要几十分钟。
 * 抽成接口后，测试塞一个假的实现就能把「陈旧 → 重建、新鲜 → 不重建」全部钉死，
 * 不必去起一个 Redis。
 *
 * <p>它刻意<b>只</b>暴露这两个动作。链路健康与否是运行时状态，重建是恢复手段，
 * 除此之外任何东西（比如「从哪读到哪」）都不属于这个契约。
 */
public interface ProgressLink {

    /**
     * 上一次「确认链路还活着」的时刻（epoch 毫秒）。
     *
     * <p>取「订阅建立时刻」与「最后一条消息到达时刻」的较大者：
     * 前者保证刚建好订阅不会立刻被判死，后者保证连上之后有消息就一直算活着。
     * 返回 {@code 0} 表示从未建立过订阅（没人订阅，谈不上死活）。
     */
    long lastSignalAt();

    /**
     * 自上次建立订阅以来，是否至少收到过一条消息。
     *
     * <p>这是链路「被证明活着」的<b>唯一</b>依据，也是唯一不会说谎的判据：
     * {@link #lastSignalAt()} 在重建订阅后会被重置成「刚刚」，只能回答「多久没动静」，
     * 不能回答「到底通没通」。宣布恢复必须用这个：重建不等于恢复，
     * 只有真的收到东西才算 —— 否则日志会报出一个自己都没验证过的「已恢复」。
     */
    boolean isConfirmedAlive();

    /**
     * 拆掉当前订阅并重新建一条。
     *
     * <p>这是<b>唯一</b>能从「连接已死但没人知道」里恢复的动作，所以看门狗一旦判定陈旧就必须调它，
     * 不能只是打个日志了事。
     */
    void recreateSubscription();
}
